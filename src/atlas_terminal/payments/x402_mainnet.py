"""Receive Base USDC with the official SDK; no payer wallet or signing key."""

import os
from typing import Any

import httpx
from x402.http import HTTPFacilitatorClientSync
from x402.http.facilitator_client_base import CreateHeadersAuthProvider, FacilitatorConfig
from x402.schemas import PaymentRequirements

from atlas_terminal.errors import AtlasError
from atlas_terminal.payments.common import (
    MAINNET_ASSET,
    MAINNET_NETWORK,
    PaymentQuote,
    validate_mainnet,
)
from atlas_terminal.payments.reconciliation import BaseSepoliaReconciler
from atlas_terminal.payments.x402_testnet import TestnetAdapter
from atlas_terminal.security import private_library_logs

CDP_FACILITATOR = "https://api.cdp.coinbase.com/platform/v2/x402"


def cdp_headers() -> dict[str, dict[str, str]]:
    """Short-lived, endpoint-bound API authentication, generated by the official CDP SDK."""
    try:
        from cdp.auth.utils.jwt import JwtOptions, generate_jwt  # type: ignore[import-untyped]

        key_id = os.environ["CDP_API_KEY_ID"]
        key_secret = os.environ["CDP_API_KEY_SECRET"]
        return {
            name: {
                "Authorization": "Bearer "
                + generate_jwt(
                    JwtOptions(
                        api_key_id=key_id,
                        api_key_secret=key_secret,
                        request_method="GET" if name == "supported" else "POST",
                        request_host="api.cdp.coinbase.com",
                        request_path=f"/platform/v2/x402/{name}",
                        expires_in=120,
                    )
                )
            }
            for name in ("supported", "verify", "settle")
        }
    except Exception:
        raise AtlasError(
            "CONFIG_REQUIRED", "Configure private CDP credentials and the seller extra."
        ) from None


class MainnetAdapter(TestnetAdapter):
    network = MAINNET_NETWORK

    def __init__(self, *, facilitator: Any = None) -> None:
        private_library_logs()
        owned = None
        if facilitator is None:
            # Validate authentication locally; do not make a source or payment request at startup.
            cdp_headers()
            owned = httpx.Client(timeout=30, follow_redirects=False)
            facilitator = HTTPFacilitatorClientSync(
                FacilitatorConfig(
                    url=CDP_FACILITATOR,
                    http_client=owned,
                    timeout=30,
                    auth_provider=CreateHeadersAuthProvider(cdp_headers),
                )
            )
        super().__init__(CDP_FACILITATOR, facilitator=facilitator)
        self.http = owned

    @staticmethod
    def requirements(quote: PaymentQuote) -> PaymentRequirements:
        p = quote.pricing
        validate_mainnet(p.network, p.asset, p.pay_to)
        if p.mode != "mainnet" or p.scheme != "exact" or p.decimals != 6:
            raise AtlasError("POLICY_DENIED", "Unsupported seller mainnet price tuple.")
        return PaymentRequirements(
            scheme="exact",
            network=MAINNET_NETWORK,
            asset=MAINNET_ASSET,
            amount=p.amount_atomic,
            pay_to=p.pay_to,
            max_timeout_seconds=300,
            extra={"name": "USD Coin", "version": "2", "assetTransferMethod": "eip3009"},
        )


class BaseMainnetReconciler(BaseSepoliaReconciler):
    network = MAINNET_NETWORK
    asset = MAINNET_ASSET
    chain_id = 8453
    mode = "mainnet"

    def validate_quote(self, quote: PaymentQuote) -> None:
        validate_mainnet(quote.pricing.network, quote.pricing.asset, quote.pricing.pay_to)
